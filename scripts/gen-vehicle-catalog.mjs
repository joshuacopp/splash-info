// Regenerates apps/damage-worker/src/vehicle-catalog.ts, the make/model list
// behind the claim form's Vehicle Make / Model suggestions.
//
//   node scripts/gen-vehicle-catalog.mjs
//
// Source: NHTSA vPIC (free, no key). Models are fetched per make for the three
// vehicle types a car wash sees (passenger car, MPV = SUVs/minivans, truck =
// pickups). Not year-aware: a make's list is every model it has ever sold here.
// Re-run once a year to pick up new models.
import { writeFileSync } from "node:fs";

// Display name -> vPIC make name. Kept to brands sold new in the US since
// ~1995 plus a few common older ones, so the list stays short and relevant.
const MAKES = {
  Acura: "acura", "Alfa Romeo": "alfa romeo", Audi: "audi", BMW: "bmw", Buick: "buick",
  Cadillac: "cadillac", Chevrolet: "chevrolet", Chrysler: "chrysler", Dodge: "dodge",
  Fiat: "fiat", Ford: "ford", Genesis: "genesis", GMC: "gmc", Honda: "honda",
  Hummer: "hummer", Hyundai: "hyundai", Infiniti: "infiniti", Jaguar: "jaguar",
  Jeep: "jeep", Kia: "kia", "Land Rover": "land rover", Lexus: "lexus",
  Lincoln: "lincoln", Lucid: "lucid", Maserati: "maserati", Mazda: "mazda",
  "Mercedes-Benz": "mercedes-benz", Mercury: "mercury", Mini: "mini",
  Mitsubishi: "mitsubishi", Nissan: "nissan", Polestar: "polestar", Pontiac: "pontiac",
  Porsche: "porsche", Ram: "ram", Rivian: "rivian", Saab: "saab", Saturn: "saturn",
  Subaru: "subaru", Suzuki: "suzuki", Tesla: "tesla", Toyota: "toyota",
  Volkswagen: "volkswagen", Volvo: "volvo"
};
const TYPES = ["car", "mpv", "truck"];
// vPIC's "truck" and "mpv" types cover pickups, SUVs and vans (needed: F-150,
// Silverado, Ram 1500) but also medium/heavy commercial chassis that never come
// through a car wash (Ford LT9000, GMC WHL, motorhome chassis). The filter runs
// on those two types only; passenger-car lists are kept as-is, so short real
// names there (Kia K900, Chevy SS) are safe. Volvo sells no pickups here, so
// its truck list is all semi tractors.
const NO_TRUCKS = new Set(["Volvo"]);
const KEEP = new Set(["t100", "ssr"]);
function keepNonCarModel(m) {
  if (KEEP.has(m.toLowerCase())) return true;
  if (/chassis|motorhome|recreational vehicle|military|hearse|police|\bbus\b|cab (over|behind)|conventional|tilt|forward|hi-cube|\bton\b|series|gmt-|^'/i.test(m)) return false;
  if (/^\d+$/.test(m)) return true; // Ram 1500 / 2500
  if (/^[A-Z]{1,5}\d{3,5}$/.test(m)) return false; // Ford LT9000, F7000
  if (m.length <= 4 && /\d/.test(m)) return false; // Chevy C7, B7, U100
  if (/^[A-Z]{2,4}$/.test(m)) return false; // GMC WHL, NE, ACL
  return true;
}
async function models(make, type) {
  const url = `https://vpic.nhtsa.dot.gov/api/vehicles/GetModelsForMakeYear/make/${encodeURIComponent(make)}/vehicletype/${type}?format=json`;
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const body = await res.json();
      return (body.Results ?? []).map((r) => String(r.Model_Name ?? "").trim()).filter(Boolean);
    } catch (err) {
      if (attempt >= 4) throw new Error(`${make}/${type}: ${err.message}`);
      await new Promise((r) => setTimeout(r, 1000 * attempt));
    }
  }
}

const catalog = {};
for (const [display, query] of Object.entries(MAKES)) {
  const types = TYPES.filter((t) => t !== "truck" || !NO_TRUCKS.has(display));
  const lists = await Promise.all(types.map((t) => models(query, t)));
  const all = lists.flatMap((list, n) => (types[n] === "car" ? list : list.filter(keepNonCarModel)));
  // Same model under two types (e.g. a car and an MPV listing) -> one entry.
  const seen = new Map();
  for (const m of all) if (!seen.has(m.toLowerCase())) seen.set(m.toLowerCase(), m);
  catalog[display] = [...seen.values()].sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }));
  if (!catalog[display].length) console.warn(`warning: no models for ${display}`);
  console.log(display, catalog[display].length);
}

// vPIC files Scion under Toyota as "Scion tC" etc.; customers type the make as Scion.
catalog.Scion = catalog.Toyota.filter((m) => /^Scion /.test(m)).map((m) => m.slice(6));

const out = `// GENERATED by scripts/gen-vehicle-catalog.mjs from NHTSA vPIC on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand; re-run the script. Make -> models, for the claim
// form's Vehicle Make / Model suggestions (served at /claims-api/vehicle-catalog).
// Suggestions only: the form still accepts anything typed.

export const VEHICLE_CATALOG: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(catalog, null, 2)};
`;
writeFileSync(new URL("../apps/damage-worker/src/vehicle-catalog.ts", import.meta.url), out);
console.log("makes:", Object.keys(catalog).length, "models:", Object.values(catalog).reduce((n, m) => n + m.length, 0));
